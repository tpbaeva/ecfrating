#!/usr/bin/env python3
"""
Generates tests/cases.js from the Python reference implementation, and checks
that the table in ecf.js matches python/ecf_table.csv.

Run from anywhere:  python3 tests/make_cases.py
Then open tests/test.html in a browser to check the JS gives the same answers.
"""

import json
import random
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / 'python'))

from ecf_rating import (get_table, get_update, get_month_update,  # noqa: E402
                        get_new_rating)


def check_js_table(table):
    js = (ROOT / 'ecf.js').read_text()
    rows = re.findall(r'\[(\d+), (\d+), ([\d.]+)\]', js)
    js_table = [(int(a), int(b), float(c)) for a, b, c in rows]
    if js_table != table:
        sys.exit('ecf.js table does not match python/ecf_table.csv')
    print(f'ecf.js table matches CSV ({len(table)} rows)')


def make_cases(table):
    own_ratings = [800, 996, 1500, 2100]
    diffs = [0, 3, 4, 10, 11, 100, 329, 344, 345, 391, 392, 1000]
    cases = []
    for own in own_ratings:
        for d in diffs:
            for opp in {own + d, own - d}:
                if opp < 0:
                    continue
                for result in (1, 0.5, 0):
                    update = get_update(own, opp, result, table)
                    cases.append([own, opp, result, round(update, 1)])
    return cases


def make_total_cases(table):
    # game counts either side of the K caps (17/18 for juniors, 35/36 for adults)
    rng = random.Random(1)
    cases = []
    for own in (110, 1500):
        for n in (1, 3, 17, 18, 35, 36, 40):
            for bias in (1, 0.5, 0):
                games = [[rng.randint(own - 450, own + 450),
                          bias if rng.random() < 0.7 else rng.choice((1, 0.5, 0))]
                         for _ in range(n)]
                # None = only the entered games; below n is ignored; above n raises the cap
                for month in (None, n - 1, n + 20):
                    for junior in (True, False):
                        changes, k = get_month_update(own, games, junior, table, month)
                        total = sum(changes)
                        cases.append([own, games, junior, month,
                                      [round(c, 6) for c in changes], round(total, 6),
                                      round(k, 6), round(get_new_rating(own, total), 6)])
    return cases


if __name__ == '__main__':
    table = get_table()
    check_js_table(table)
    cases = make_cases(table)
    total_cases = make_total_cases(table)
    out = ROOT / 'tests' / 'cases.js'
    out.write_text('// Generated by tests/make_cases.py\n'
                   '// [own, opponent, result, update]\n'
                   'const CASES = ' + json.dumps(cases) + ';\n'
                   '// [own, [[opponent, result], ...], junior, games this month, changes, total, k, new rating]\n'
                   'const TOTAL_CASES = ' + json.dumps(total_cases) + ';\n')
    print(f'wrote {len(cases)} game cases and {len(total_cases)} total cases '
          f'to {out.relative_to(ROOT)}')
